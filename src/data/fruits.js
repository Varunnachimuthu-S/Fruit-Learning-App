// Helper function to get fruits by category
export const getFruitsByCategory = (category) => {
  return fruits.filter((fruit) => fruit.category === category);
};

// Helper function to get random fruits
export const getRandomFruits = (count) => {
  const shuffled = [...fruits].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
};

// Helper function to get fruit by id
export const getFruitById = (id) => {
  return fruits.find((fruit) => fruit.id === id);
};
